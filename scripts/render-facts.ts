export function renderReadmeBlockEn(f: Facts, docMapCheckedAt: string | null): string {
  const est = estimateFullRun("en");
  const credit = Number(f.signup.startingCredit.replace(/[^\d.]/g, ""));
  return [
    "<!-- facts:start -->",
    "```",
    `Last verified: ${f.lastVerified} | Model: ${f.model.pinned} | SDK: ${f.sdk.js} ${f.sdk.jsVersion}`,
    `Official docs diff check: ${docMapCheckedAt ? `✅ ${docMapCheckedAt}` : "not run yet"}`,
    "```",
    "",
    `Estimated Jev cost of sending every English sample request once in live mode: about ${formatUSD(est.costUSD)} (${est.inputTokens.toLocaleString("en-US")} input tokens, ${((est.costUSD / credit) * 100).toPrecision(2)}% of the ${f.signup.startingCredit} sign-up credit)${syntheticNote(est.syntheticShare, "en")}. Claude usage in Advanced B is billed separately`,
    "<!-- facts:end -->",
  ].join("\n");
}

const BLOCK = /<!-- facts:start -->[\s\S]*?<!-- facts:end -->/;

function docMapCheckedAt(): string | null {
  const file = join(ROOT, "data", "doc-map.json");
  if (!existsSync(file)) return null;
  return (JSON.parse(readFileSync(file, "utf8")) as { checkedAt: string | null }).checkedAt;
}

async function main() {
  const check = process.argv.includes("--check");
  const checkedAt = docMapCheckedAt();
  const readmePath = join(ROOT, "README.md");
  const readme = readFileSync(readmePath, "utf8");
  if (!BLOCK.test(readme))
    throw new Error("README.md に <!-- facts:start --> 〜 <!-- facts:end --> がありません");

  const readmeEnPath = join(ROOT, "README.en.md");
  const readmeEn = readFileSync(readmeEnPath, "utf8");
  if (!BLOCK.test(readmeEn))
    throw new Error("README.en.md has no <!-- facts:start --> ... <!-- facts:end --> block");

  const outputs: [string, string][] = [
    [join(ROOT, "docs", "_generated", "facts.md"), renderFactsMd(facts)],
    [join(ROOT, "docs", "_generated", "last-verified.md"), renderLastVerifiedMd(facts, checkedAt)],
    [readmePath, readme.replace(BLOCK, renderReadmeBlock(facts, checkedAt))],
    [join(ROOT, "docs", "_generated", "facts.en.md"), renderFactsMdEn(facts)],
    [readmeEnPath, readmeEn.replace(BLOCK, renderReadmeBlockEn(facts, checkedAt))],
  ];

  const stale = outputs.filter(
    ([file, content]) => !existsSync(file) || readFileSync(file, "utf8") !== content,
  );
  if (check) {
    if (stale.length > 0) {
      console.error(
        `生成物が古くなっています。npm run facts を実行してください:\n${stale.map(([f]) => `  - ${relative(ROOT, f)}`).join("\n")}`,
      );
      process.exitCode = 1;
    }
    return;
  }
  for (const [file, content] of stale) writeFileSync(file, content);
  console.log(
    stale.length === 0 ? "変更なし" : `更新: ${stale.map(([f]) => relative(ROOT, f)).join(", ")}`,
  );
}

runMain(import.meta.url, main);
