export function renderLastVerifiedMd(f: Facts, docMapCheckedAt: string | null): string {
  return `# 最終確認日

${HEADER}

| 対象 | 最終確認日 | 確認方法 |
|---|---|---|
| data/facts.json（モデル・料金・レート制限など） | ${f.lastVerified} | 手動確認＋ \`npm run facts:verify\` |
| 公式ドキュメント一覧（llms.txt） | ${docMapCheckedAt ?? "未実施"} | \`npm run docmap\`（週次CI） |
`;
}

/** 費用の目安に付ける注記。見本データ（合成）がどのくらい混ざっているかで文面を変える */
export function syntheticNote(share: number, lang: "ja" | "en"): string {
  if (share === 0) return "";
  if (share === 1)
    return lang === "ja"
      ? "。※ 見本データ（合成）のトークン数からの推定"
      : ". Estimated from the token counts of the sample (synthetic) data";
  return lang === "ja"
    ? "。※ 一部は見本データ（合成）のトークン数からの推定"
    : ". Partly estimated from the token counts of the sample (synthetic) data";
}

/** lang のサンプルのリクエストを1回ずつ送ったときのトークン数。英語モードの fixture は fixtures/en/ にある */
export function estimateFullRun(lang: "ja" | "en" = "ja"): {
  inputTokens: number;
  costUSD: number;
  /** 合成データの割合。0 なら全部実測、1 なら全部見本 */
  syntheticShare: number;
} {
  const fixtures = readdirSync(FIXTURES_DIR, { recursive: true })
    .map(String)
    // errors は見本のエラー、*-claude は Anthropic の応答なので Jev の費用に含めない
    .filter(
      (f) =>
        f.endsWith(".json") &&
        !f.startsWith("errors") &&
        !/-claude\//.test(f) &&
        (lang === "en" ? f.startsWith("en/") : !f.startsWith("en/")),
    )
    .map((f) => JSON.parse(readFileSync(join(FIXTURES_DIR, f), "utf8")) as Fixture);
  const usage = sumUsage(
    ...fixtures.map(
      (fx) =>
        (fx.response.body as { usage?: { input_tokens: number; output_tokens: number } }).usage ?? {
          input_tokens: 0,
          output_tokens: 0,
        },
    ),
  );
  return {
    inputTokens: usage.input_tokens,
    costUSD: costUSD(usage),
    syntheticShare:
      fixtures.length === 0
        ? 0
        : fixtures.filter((fx) => fx.meta.source === "synthetic").length / fixtures.length,
  };
}

export function renderReadmeBlock(f: Facts, docMapCheckedAt: string | null): string {
  const est = estimateFullRun();
  return [
    "<!-- facts:start -->",
    "```",
    `最終検証: ${f.lastVerified} ｜ 対象モデル: ${f.model.pinned} ｜ SDK: ${f.sdk.js} ${f.sdk.jsVersion}`,
    `公式ドキュメント差分チェック: ${docMapCheckedAt ? `✅ ${docMapCheckedAt}` : "未実施"}`,
    "```",
    "",
    `全サンプルのリクエストを1回ずつ live で送ったときの Jev の費用の目安: 約 ${formatUSD(est.costUSD)}（入力 ${est.inputTokens.toLocaleString("en-US")} トークン、新規クレジット ${f.signup.startingCredit} の ${((est.costUSD / Number(f.signup.startingCredit.replace(/[^\d.]/g, ""))) * 100).toPrecision(2)}%）${syntheticNote(est.syntheticShare, "ja")}。応用B の Claude の費用は別にかかります`,
    "<!-- facts:end -->",
  ].join("\n");
}

